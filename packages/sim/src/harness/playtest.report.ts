// Writes the bot run into docs/PLAYTEST.md. Not part of `npm test`:
// run it with `npm run playtest` from the repo root.
import { it, expect } from "vitest";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { runPlaytest, playtestMarkdown } from "./playtestHarness.js";
import { runProgression, progressionText, livingText } from "./progressionHarness.js";

const START = "<!-- sim-playtest:start -->";
const END = "<!-- sim-playtest:end -->";

it("writes docs/PLAYTEST.md", () => {
  const report = runPlaytest();
  const block = `${START}\n${playtestMarkdown(report)}\n${END}`;
  const file = resolve(process.cwd(), "../../docs/PLAYTEST.md");
  const old = existsSync(file) ? readFileSync(file, "utf8") : "# Playtest\n";
  // Replace our marked block; otherwise insert it right after the title line.
  let next: string;
  if (old.includes(START) && old.includes(END)) {
    next = old.slice(0, old.indexOf(START)) + block + old.slice(old.indexOf(END) + END.length);
  } else {
    const cut = old.indexOf("\n") + 1;
    next = `${old.slice(0, cut)}\n${block}\n\n${old.slice(cut).replace(/^\r?\n/, "")}`;
  }
  writeFileSync(file, next.endsWith("\n") ? next : `${next}\n`);
  console.log(`playtest: ${report.ticksRun} ticks, ${report.errors.length} errors, ${report.failedAsserts.length} failed asserts -> ${file}`);
  expect(report.ticksRun).toBeGreaterThan(0);
});

const PSTART = "<!-- sim-progression:start -->";
const PEND = "<!-- sim-progression:end -->";

it("writes the progression report into docs/PLAYTEST.md", () => {
  const fast = runProgression();
  const idle = runProgression({ turnEvery: 18_000 });
  const body = [
    "## Progression harness (new realm to Keep III)",
    "",
    "Generated by `npm run playtest` (`packages/sim/src/harness/progressionHarness.ts`). Measure only; it never edits a table.",
    "",
    "Attentive player (bot looks every 20 s):",
    "",
    "```",
    progressionText(fast),
    "```",
    "",
    "Low-touch player (bot looks every 30 min):",
    "",
    "```",
    progressionText(idle),
    "```",
    "",
    "### Living realm (same two runs)",
    "",
    "War phase timing, NPC caravans and whispers, and worker posts. Measure only.",
    "",
    "Attentive:",
    "",
    "```",
    livingText(fast),
    "```",
    "",
    "Low-touch:",
    "",
    "```",
    livingText(idle),
    "```",
  ].join("\n");
  const block = `${PSTART}\n${body}\n${PEND}`;
  const file = resolve(process.cwd(), "../../docs/PLAYTEST.md");
  const old = readFileSync(file, "utf8");
  const next =
    old.includes(PSTART) && old.includes(PEND)
      ? old.slice(0, old.indexOf(PSTART)) + block + old.slice(old.indexOf(PEND) + PEND.length)
      : old.replace(END, `${END}\n\n${block}`);
  writeFileSync(file, next);
  console.log(progressionText(fast));
  expect(fast.reachedKeep).toBeGreaterThan(0);
});
