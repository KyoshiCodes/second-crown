/**
 * Resolves the active theme pack based on holiday override/calendar or current season.
 */
export function resolveActiveThemePack(season: string, holidayId: string): ThemePack {
  if (holidayId && holidayId !== "none" && holidayId in THEME_PACKS) {
    return THEME_PACKS[holidayId as ThemePackId];
  }
  const s = season.toLowerCase() as ThemePackId;
  return THEME_PACKS[s] ?? THEME_PACKS.spring;
}
